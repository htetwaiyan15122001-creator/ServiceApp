  Future<void> _checkSignatureStatus(BuildContext context, HistoryJob job) async {
    if (!SharePointService.isSignatureLinkConfigured) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text(tr("Signature-link flow isn't configured yet — see sharepoint_service.dart"))),
      );
      return;
    }

    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(content: Text(tr("Checking..."))),
    );

    final signatureBase64 = await SharePointService.checkSignatureStatus(job.id);

    if (signatureBase64 != null) {
      JobHistoryPage.markSignatureCollected(job.id);
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text(tr("Customer has signed — job marked complete"))),
      );
    } else {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text(tr("Not signed yet"))),
      );
    }
  }

