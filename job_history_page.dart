/// True if [day] falls within a job's scheduled range — a single day if
/// only `expectedDate` is set, or the full span if `endDate` is also set.
bool jobActiveOn(HistoryJob job, DateTime day) {
  if (job.expectedDate == null) return false;
  final start = DateTime(job.expectedDate!.year, job.expectedDate!.month, job.expectedDate!.day);
  final end = job.endDate != null
      ? DateTime(job.endDate!.year, job.endDate!.month, job.endDate!.day)
      : start;
  final d = DateTime(day.year, day.month, day.day);
  return !d.isBefore(start) && !d.isAfter(end);
}

