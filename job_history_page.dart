  /// Restores created jobs saved from a previous session. Call once at
  /// startup, after AppStorage.init().
  static void loadSaved() {
    final raw = AppStorage.prefs.getString(_jobsPrefKey);
    if (raw == null) return;
    try {
      final decoded = jsonDecode(raw) as List;
      createdJobsNotifier.value =
          decoded.map((e) => HistoryJob.fromJson(e as Map<String, dynamic>)).toList();
    } catch (_) {
      // Corrupt or outdated saved data — start fresh rather than crash.
    }
  }

  static void _persist() {
    final encoded = jsonEncode(createdJobsNotifier.value.map((j) => j.toJson()).toList());
    AppStorage.prefs.setString(_jobsPrefKey, encoded);
  }

  /// Adds a newly-created job (from Assign > Create) and shows it here.
  static HistoryJob addJob({
    required String title,
    String jobType = jobTypeProject,
    String? serviceSubType,
    String? product,
    String? description,
    DateTime? expectedDate,
    DateTime? endDate,
    String? location,
    String? assignedTo,
    String? action,
    String? task,
  }) {
    final job = HistoryJob(
      id: DateTime.now().microsecondsSinceEpoch.toString(),
      title: title,
      subtitle: location ?? "",
      time: expectedDate != null ? formatJobTime(expectedDate) : formatJobTime(DateTime.now()),
      status: action ?? "Unassigned",
      assignedTo: assignedTo,
      action: action,
      task: task,
      jobType: jobType,
      serviceSubType: serviceSubType,
      product: product,
      description: description,
      expectedDate: expectedDate,
      endDate: endDate,
      location: location,
    );
    createdJobsNotifier.value = [job, ...createdJobsNotifier.value];
    _persist();
    return job;
  }

  /// Updates an existing created job (from Assign editing an entry).
  static void updateJob(
    String id, {
    required String title,
    String jobType = jobTypeProject,
    String? serviceSubType,
    String? product,
    String? description,
    DateTime? expectedDate,
    DateTime? endDate,
    String? location,
    String? assignedTo,
    String? action,
    String? task,
  }) {
    for (final j in createdJobsNotifier.value) {
      if (j.id == id) {
        j.title = title;
        j.jobType = jobType;
        j.serviceSubType = serviceSubType;
        j.product = product;
        j.description = description;
        j.expectedDate = expectedDate;
        j.endDate = endDate;
        j.location = location;
        j.subtitle = location ?? "";
        j.time = expectedDate != null ? formatJobTime(expectedDate) : j.time;
        j.assignedTo = assignedTo;
        j.action = action;
        j.task = task;
        j.status = action ?? "Unassigned";
        break;
      }
    }
    createdJobsNotifier.value = [...createdJobsNotifier.value];
    _persist();
  }

  /// Finds a job by id across both demo rows and created jobs.
  static HistoryJob? findJob(String id) {
    for (final j in [..._demoJobs, ...createdJobsNotifier.value]) {
      if (j.id == id) return j;
    }
    return null;
  }

  /// Called when a service report is submitted without the customer's
  /// signature (they weren't on-site). Flags the job so it shows up as
  /// needing a signature, due by the end of today.
  static void markPendingSignature(String id) {
    final job = findJob(id);
    if (job == null) return;
    final now = DateTime.now();
    job.signaturePending = true;
    job.signatureDueBy = DateTime(now.year, now.month, now.day, 23, 59);
    job.status = "Pending Signature";
    _refresh();
  }

  /// Called once the engineer goes back and actually collects the
  /// customer's signature for a job that was previously pending.
  static void markSignatureCollected(String id, {String? signatureBase64}) {
    final job = findJob(id);
    if (job == null) return;
    job.signaturePending = false;
    job.signatureDueBy = null;
    job.status = "Completed";
    if (signatureBase64 != null) {
      job.signatureBase64 = signatureBase64;
    }
    _refresh();
  }

  /// Saves the submitted service report's photos/signature onto the job
  /// locally (SharedPreferences), independent of whether the SharePoint
  /// backend upload succeeds. This means nothing is lost while the backend
  /// isn't configured yet.
  static void attachReportPhotos(
    String id, {
    required List<String> photoBase64,
    required List<String> photoFileNames,
    String? signatureBase64,
  }) {
    final job = findJob(id);
    if (job == null) return;
    job.photoBase64 = photoBase64;
    job.photoFileNames = photoFileNames;
    if (signatureBase64 != null) {
      job.signatureBase64 = signatureBase64;
    }
    _refresh();
  }

  /// Called when the engineer finishes a service report on-site (customer
  /// signed immediately, no remote signature needed). Marks the job done
  /// so it can't be started again until the manager re-assigns it.
  static void markCompleted(String id) {
    final job = findJob(id);
    if (job == null) return;
    job.signaturePending = false;
    job.signatureDueBy = null;
    job.status = "Completed";
    _refresh();
  }

  /// Forces listeners to rebuild — needed even when only a demo job's
  /// mutable fields changed, since they aren't part of the notifier's list.
  static void _refresh() {
    createdJobsNotifier.value = [...createdJobsNotifier.value];
    _persist();
  }

