/// A single job/project entry. Used both for the built-in demo rows and
/// for jobs created from the Assign tab.
class HistoryJob {
  final String id;
  String title;
  String subtitle; // shown in list tiles — the location
  String time;
  String status;
  String? assignedTo;
  String? action;
  String? task; // sub-task checklist item, depends on [action]
  String jobType; // jobTypeProject or jobTypeService
  String? serviceSubType; // serviceSubTypeService or serviceSubTypeAfterService, only when jobType == jobTypeService

  // Extra detail captured by the Assign form.
  String? product; // e.g. "KNX F10SW"
  String? description;
  DateTime? expectedDate; // start date when the job spans a range
  DateTime? endDate; // end date of the scheduled range; null = single day
  String? location;

  // Signature tracking — set when the customer wasn't on-site to sign
  // at the time the engineer submitted the service report.
  bool signaturePending;
  DateTime? signatureDueBy;

  // Service report attachments — saved locally (SharedPreferences) as soon
  // as the report is submitted, regardless of whether the SharePoint
  // backend is configured/reachable, so nothing is lost while that's
  // being set up.
  List<String> photoBase64;
  List<String> photoFileNames;
  String? signatureBase64;

  HistoryJob({
    required this.id,
    required this.title,
    required this.subtitle,
    required this.time,
    required this.status,
    this.assignedTo,
    this.action,
    this.task,
    this.jobType = jobTypeProject,
    this.serviceSubType,
    this.product,
    this.description,
    this.expectedDate,
    this.endDate,
    this.location,
    this.signaturePending = false,
    this.signatureDueBy,
    List<String>? photoBase64,
    List<String>? photoFileNames,
    this.signatureBase64,
  })  : photoBase64 = photoBase64 ?? [],
        photoFileNames = photoFileNames ?? [];

  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'subtitle': subtitle,
        'time': time,
        'status': status,
        'assignedTo': assignedTo,
        'action': action,
        'task': task,
        'jobType': jobType,
        'serviceSubType': serviceSubType,
        'product': product,
        'description': description,
        'expectedDate': expectedDate?.toIso8601String(),
        'endDate': endDate?.toIso8601String(),
        'location': location,
        'signaturePending': signaturePending,
        'signatureDueBy': signatureDueBy?.toIso8601String(),
        'photoBase64': photoBase64,
        'photoFileNames': photoFileNames,
        'signatureBase64': signatureBase64,
      };

  factory HistoryJob.fromJson(Map<String, dynamic> json) => HistoryJob(
        id: json['id'] as String,
        title: json['title'] as String,
        subtitle: json['subtitle'] as String,
        time: json['time'] as String,
        status: json['status'] as String,
        assignedTo: json['assignedTo'] as String?,
        action: json['action'] as String?,
        task: json['task'] as String?,
        jobType: json['jobType'] as String? ?? jobTypeProject,
        serviceSubType: json['serviceSubType'] as String?,
        product: json['product'] as String?,
        description: json['description'] as String?,
        expectedDate: json['expectedDate'] != null ? DateTime.tryParse(json['expectedDate'] as String) : null,
        endDate: json['endDate'] != null ? DateTime.tryParse(json['endDate'] as String) : null,
        location: json['location'] as String?,
        signaturePending: json['signaturePending'] as bool? ?? false,
        signatureDueBy: json['signatureDueBy'] != null ? DateTime.tryParse(json['signatureDueBy'] as String) : null,
        photoBase64: (json['photoBase64'] as List?)?.map((e) => e as String).toList(),
        photoFileNames: (json['photoFileNames'] as List?)?.map((e) => e as String).toList(),
        signatureBase64: json['signatureBase64'] as String?,
      );
}

