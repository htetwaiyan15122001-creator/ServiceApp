/// Matches a job against a quick-filter value from [quickStatusFilters].
/// Handles "Assigned" as a special case (assignedTo != null) since it isn't
/// a real `status` value; everything else is a plain status equality check.
bool jobMatchesStatusFilter(HistoryJob job, String? filter) {
  if (filter == null) return true;
  if (filter == "Assigned") return job.assignedTo != null;
  return job.status == filter;
}

